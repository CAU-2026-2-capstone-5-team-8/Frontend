import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const root = dirname(require.resolve("katex/package.json"));
let css = await readFile(resolve(root, "dist/katex.min.css"), "utf8");
// Embed WOFF2 fonts so native WebViews and web previews need no CDN or asset server.
const fonts = [
  ...new Set(
    [...css.matchAll(/url\(fonts\/([^)]*\.woff2)\)/g)].map((m) => m[1]),
  ),
];
for (const font of fonts) {
  const data = await readFile(resolve(root, "dist/fonts", font));
  css = css.replaceAll(
    `url(fonts/${font})`,
    `url(data:font/woff2;base64,${data.toString("base64")})`,
  );
}
css = css.replace(/,url\(fonts\/[^)]+\) format\("(?:woff|truetype)"\)/g, "");
if (css.includes("url(fonts/")) throw new Error("Unbundled KaTeX font");
const version = JSON.parse(
  await readFile(resolve(root, "package.json"), "utf8"),
).version;
await writeFile(
  new URL("../src/lib/katexStyles.ts", import.meta.url),
  `// Generated by scripts/build-katex-css.mjs. KaTeX ${version}; MIT license, see THIRD_PARTY_NOTICES.md.\nexport const katexStyles = ${JSON.stringify(css)};\n`,
);
